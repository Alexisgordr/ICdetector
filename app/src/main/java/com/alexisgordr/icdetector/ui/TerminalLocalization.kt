/**
 * Traducción al inglés de las líneas del terminal y de las explicaciones de diagnóstico, que el
 * servicio genera en castellano. Es solo presentación: el texto original se guarda y se exporta tal
 * cual.
 *
 * v2.10.6 — La tabla se aplica de la frase más larga a la más corta. Antes se aplicaba en el orden
 * en que estaba escrita, y una palabra suelta ("anómala") se traducía dentro de una frase larga
 * ("La condición anómala…") antes de que la frase completa pudiera reconocerse, dejando líneas a
 * medio traducir. Separada de Terminal.kt para poder probarla en la JVM.
 */
internal fun localizeTerminalLine(line: String): String {
    var translated = line
    orderedReplacements.forEach { (source, target) -> translated = translated.replace(source, target, ignoreCase = true) }
    return translated
}

